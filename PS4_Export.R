# =============================================================================
# PS4_Export.R  -  Empirical Methods HS 2026, Problem Set 4
# Exports every number shown on the website (docs/) from our PS3 replication.
#
# Run from the repository root, after PS3_Solution.R works there:
#   Rscript PS4_Export.R
# Input : PS3_Solution.R and the two raw Excel files (sourced, nothing modified)
# Output: docs/data/results.js  (one JS object, window.RESULTS; plain JS instead
#         of JSON so that docs/index.html also works when opened as a local file)
# Packages: those of PS3_Solution.R, plus jsonlite
# =============================================================================

## (a) Run the replication ----
# PS3_Solution.R starts with rm(list = ls()) and set.seed(12345), and creates
# d, m, ext, sens, ovb, ... . All numbers below come from these objects.
source("PS3_Solution.R", echo = FALSE)
library(jsonlite)
if (!dir.exists("docs/data")) dir.create("docs/data", recursive = TRUE)

## (b) Panel data for the scatter plot ----
panel <- d[, c("bank", "year", "env", "roa", "roe", "npa")]

## (c) Controls lab: ENV slope for every subset of the six controls ----
# Pooled OLS (as the paper's ROE model), conventional SE, 2 outcomes x 64
# control sets x 2 samples (all banks / without IDFC First) = 256 regressions.
subsets <- unlist(lapply(0:length(ctrl), function(k) combn(ctrl, k, simplify = FALSE)),
                  recursive = FALSE)
samples <- list(all = d, no_idfc = d[d$bank != "IDFC First Bank", ])
grid <- do.call(rbind, lapply(names(samples), function(s) {
  do.call(rbind, lapply(c("roa", "roe"), function(y) {
    do.call(rbind, lapply(subsets, function(w) {
      fit <- lm(reformulate(c("env", w), response = y), data = samples[[s]])
      ct  <- summary(fit)$coefficients["env", ]
      ci  <- confint(fit)["env", ]
      data.frame(sample = s, y = y, controls = paste(sort(w), collapse = "+"),
                 b = ct[["Estimate"]], se = ct[["Std. Error"]], p = ct[["Pr(>|t|)"]],
                 lo = ci[[1]], hi = ci[[2]], n = nobs(fit))
    }))
  }))
}))
rownames(grid) <- NULL
# Check: the grid reproduces the sensitivity table of PS3 (d5)
chk <- grid[grid$sample == "all" & grid$controls %in% c("", paste(sort(ctrl), collapse = "+")), ]
print(chk[, c("y", "controls", "b")], digits = 4)
stopifnot(abs(chk$b[chk$y == "roe" & chk$controls == ""] - sens$roe[sens$controls == "none"]) < 1e-12,
          abs(chk$b[chk$y == "roe" & chk$controls != ""] - sens$roe[sens$controls == "all six"]) < 1e-12)

## (d) Main table (PS3 Table 1): POLS, RE, FE for ROA and ROE ----
main <- do.call(rbind, lapply(c("roa", "roe"), function(y) {
  do.call(rbind, lapply(c(POLS = "po", RE = "re", FE = "fe"), function(k) {
    ct <- coeftest(m[[y]][[k]])
    data.frame(y = y, model = names(which(c(POLS = "po", RE = "re", FE = "fe") == k)),
               term = rownames(ct), b = ct[, 1], se = ct[, 2], p = ct[, 4])
  }))
}))
main <- main[main$term %in% xs, ]
rownames(main) <- NULL

## (e) Extension table (PS3 Table 2): specifications A-G ----
spec_labels <- c(A = "Paper's model", B = "Bank fixed effects",
                 C = "Bank + year fixed effects (our main model)",
                 D = "C without IDFC First Bank", E = "C with last year's ENV score",
                 F = "First differences", G = "E without fixed effects")
ext$label <- spec_labels[ext$spec]

## (f) Key facts for the text ----
facts <- list(
  n_banks = length(unique(d$bank)), n_obs = nrow(d),
  years = range(d$year), n_years = length(unique(d$year)),
  mean_env = mean(d$env), sd_env = sd(d$env),
  mean_roa = mean(d$roa), mean_roe = mean(d$roe),
  cor_env_npa = cor(d$env, d$npa),
  slope_raw = list(roa = b_env("roa", NULL), roe = b_env("roe", NULL)),
  fit_raw = list(roa = as.list(coef(lm(roa ~ env, data = d))),       # line in chart 1
                 roe = as.list(coef(lm(roe ~ env, data = d)))),
  slope_npa = list(roa = b_env("roa", "npa"), roe = b_env("roe", "npa")),
  ovb = as.list(ovb[, c("b_short", "b_long", "beta_npa", "npa_on_env", "bias")]),
  within_share_env = unname(within_share["env"])
)
print(facts)

## (g) Write docs/data/results.js ----
out <- list(
  meta = list(created = format(Sys.time(), "%Y-%m-%d %H:%M %Z"),
              r_version = R.version.string, source = "PS3_Solution.R + PS4_Export.R"),
  facts = facts, panel = panel, grid = grid, main = main, ext = ext,
  labels = list(ctrl = list(age = "Bank age", size = "Bank size", lev = "Leverage",
                         capint = "Capital intensity", npa = "Bad loans (net NPA)",
                         nim = "Net interest margin"))
)
js <- paste0("// Generated by PS4_Export.R - do not edit by hand\nwindow.RESULTS = ",
             toJSON(out, dataframe = "rows", auto_unbox = TRUE, digits = 8, pretty = FALSE), ";\n")
writeLines(js, "docs/data/results.js", useBytes = TRUE)
cat("Written: docs/data/results.js (", file.size("docs/data/results.js"), "bytes )\n")
